#!/bin/bash
# Builds Lync.app (and optionally a DMG) from the Swift package.
#
#   scripts/build-app.sh            # debug build → build/Lync.app
#   scripts/build-app.sh release    # release build → build/Lync.app
#   scripts/build-app.sh release dmg   # also build/Lync.dmg
#
# A universal binary (Apple silicon and Intel). Signs ad-hoc ("-") unless SIGN_IDENTITY is set
# to a Developer ID ("Developer ID Application: Name (TEAMID)"). With NOTARY_PROFILE as well (a
# notarytool keychain profile: xcrun notarytool store-credentials <name>), the DMG is notarized
# by Apple and stapled, so it opens on any Mac without a warning. OUT_DIR puts the app and DMG
# somewhere other than build/.
# Never launches anything.
set -euo pipefail

cd "$(dirname "$0")/.."
CONFIG="${1:-debug}"
MAKE_DMG="${2:-}"
export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"

ARCHS=(--arch arm64 --arch x86_64)
swift build -c "$CONFIG" "${ARCHS[@]}"
BIN_DIR="$(swift build -c "$CONFIG" "${ARCHS[@]}" --show-bin-path)"

OUT_DIR="${OUT_DIR:-build}"
mkdir -p "$OUT_DIR"
APP="$OUT_DIR/Lync.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/WallhopMac" "$APP/Contents/MacOS/Lync"
# Sparkle, for updates without a new download (App/Updates.swift), in Contents/Frameworks.
mkdir -p "$APP/Contents/Frameworks"
cp -R "$BIN_DIR/Sparkle.framework" "$APP/Contents/Frameworks/"
install_name_tool -add_rpath "@executable_path/../Frameworks" "$APP/Contents/MacOS/Lync" 2>/dev/null || true
cp Info.plist "$APP/Contents/Info.plist"
# Figtree, the phone app's font (SIL OFL).
cp Resources/Figtree.ttf "$APP/Contents/Resources/Figtree.ttf"
# Galindo, the wordmark's font, for big titles (SIL OFL; its licence travels with it).
cp Resources/Galindo.ttf "$APP/Contents/Resources/Galindo.ttf"
cp Resources/Galindo-OFL.txt "$APP/Contents/Resources/Galindo-OFL.txt"
# The menu bar icon (a template image; generated by brand/kit/build_kit.py).
cp Resources/MenuBarIcon.png Resources/MenuBarIcon@2x.png "$APP/Contents/Resources/"
# The app's icons, one SVG per SF Symbol name it uses (generated by brand/icons/generate.mjs).
cp -R Resources/Icons "$APP/Contents/Resources/Icons"
if [ -f Resources/AppIcon.icns ]; then
  cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
  /usr/libexec/PlistBuddy -c "Add :CFBundleIconFile string AppIcon" "$APP/Contents/Info.plist"
fi

# Without a Developer ID, a "Lync Local" code-signing certificate in the login keychain (self-signed,
# made once in Keychain Access) keeps the app's identity the same from build to build, so macOS
# remembers Bluetooth, Local Network and the other permissions. Ad-hoc, every build looks like a
# new app and asks again.
# Updates keep working only while every release is signed by the same certificate: back it up.
LOCAL_IDENTITY="Lync Local"
SIGN_FLAGS=(--force --options runtime)
if [ -n "${SIGN_IDENTITY:-}" ]; then
  # Notarization needs the hardened runtime and a secure timestamp.
  IDENTITY="$SIGN_IDENTITY"
  SIGN_FLAGS+=(--timestamp)
elif security find-certificate -c "$LOCAL_IDENTITY" >/dev/null 2>&1; then
  IDENTITY="$LOCAL_IDENTITY"
else
  IDENTITY="-"
fi
# Sparkle's helpers first, inside out, then the app (Sparkle's guide for apps built outside Xcode).
SPARKLE="$APP/Contents/Frameworks/Sparkle.framework/Versions/B"
codesign "${SIGN_FLAGS[@]}" --sign "$IDENTITY" "$SPARKLE/XPCServices/Installer.xpc"
codesign "${SIGN_FLAGS[@]}" --preserve-metadata=entitlements --sign "$IDENTITY" "$SPARKLE/XPCServices/Downloader.xpc"
codesign "${SIGN_FLAGS[@]}" --sign "$IDENTITY" "$SPARKLE/Autoupdate"
codesign "${SIGN_FLAGS[@]}" --sign "$IDENTITY" "$SPARKLE/Updater.app"
codesign "${SIGN_FLAGS[@]}" --sign "$IDENTITY" "$APP/Contents/Frameworks/Sparkle.framework"
APP_FLAGS=()
# A Developer ID gives the app and Sparkle the same team; any other certificate needs Lync.entitlements.
[ -z "${SIGN_IDENTITY:-}" ] && [ "$IDENTITY" != "-" ] && APP_FLAGS+=(--entitlements Lync.entitlements)
codesign "${SIGN_FLAGS[@]}" ${APP_FLAGS[@]+"${APP_FLAGS[@]}"} --sign "$IDENTITY" "$APP"
echo "Built $APP"

if [ "$MAKE_DMG" = "dmg" ]; then
  STAGE="$(mktemp -d)"
  cp -R "$APP" "$STAGE/"
  ln -s /Applications "$STAGE/Applications"
  rm -f "$OUT_DIR/Lync.dmg"
  hdiutil create -volname "Lync" -srcfolder "$STAGE" -ov -format UDZO "$OUT_DIR/Lync.dmg" >/dev/null
  rm -rf "$STAGE"
  if [ -n "${SIGN_IDENTITY:-}" ]; then
    codesign --force --timestamp --sign "$SIGN_IDENTITY" "$OUT_DIR/Lync.dmg"
  fi
  if [ -n "${NOTARY_PROFILE:-}" ]; then
    [ -n "${SIGN_IDENTITY:-}" ] || { echo "NOTARY_PROFILE needs SIGN_IDENTITY (a Developer ID)" >&2; exit 1; }
    xcrun notarytool submit "$OUT_DIR/Lync.dmg" --keychain-profile "$NOTARY_PROFILE" --wait
    xcrun stapler staple "$OUT_DIR/Lync.dmg"
    xcrun stapler validate "$OUT_DIR/Lync.dmg"
  fi
  echo "Built $OUT_DIR/Lync.dmg"
fi
