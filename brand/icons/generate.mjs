#!/usr/bin/env node
// Builds both apps' icons from icons.json and the Bicon library.
//
//   node brand/icons/generate.mjs [path/to/icon-library]
//
// The library defaults to ~/Documents/icon-library (or $BICON_DIR). It writes:
//   android/app/src/main/java/app/wallhop/ui/design/WIcons.kt  every Android key (CamelCase), as
//       ImageVectors on a 24 × 24 viewport. Each val keeps the KDoc it has in the file now, so edit
//       those there; everything else in the file comes from here.
//   mac/Resources/Icons/<key>.svg  every Mac key (an SF Symbol name the Mac code uses), which
//       NudgeImage draws instead of the symbol. build-app.sh copies the folder into the app.
// Stroke icons get STROKE_WIDTH on the 24 grid in both apps. Run it again after editing icons.json.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, unlinkSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

/** Line weight for every stroke icon, on the 24 grid (the library's default of 1 is hairline at 14–20 pt). */
const STROKE_WIDTH = 1.5;

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const library = resolve(process.argv[2] ?? process.env.BICON_DIR ?? join(homedir(), 'Documents/icon-library'));
const manifest = JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8')).icons;
const wiconsPath = join(repo, 'android/app/src/main/java/app/wallhop/ui/design/WIcons.kt');
const macDir = join(repo, 'mac/Resources/Icons');

function svgFor({ bicon, style }) {
    if (style !== 'stroke' && style !== 'solid') throw new Error(`${bicon}: style must be stroke or solid`);
    const file = join(library, 'icons', style, `${bicon}.svg`);
    if (!existsSync(file)) throw new Error(`No ${style} icon called ${bicon} (${file})`);
    return readFileSync(file, 'utf8');
}

/** The <path>s of an icon: its data, and whether it's stroked or filled (and how). */
function paths(svg, style) {
    return [...svg.matchAll(/<path\b([^>]*?)\/?>/g)].map(([, attrs]) => {
        const attr = (name) => attrs.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
        const filled = style === 'solid' || attr('fill') === 'currentColor';
        return { d: attr('d'), stroke: !filled, evenOdd: attr('fill-rule') === 'evenodd' };
    });
}

// MARK: Android

/** The KDoc above each val in the current WIcons.kt, and the order the vals are in. */
function currentDocs(source) {
    const docs = new Map();
    const lines = source.split('\n');
    lines.forEach((line, i) => {
        const name = line.match(/^\s*val (\w+): ImageVector/)?.[1];
        if (!name) return;
        let start = i;
        if (lines[i - 1]?.trim().endsWith('*/')) {
            while (start > 0 && !lines[start - 1].trim().startsWith('/**')) start--;
            start--;
        }
        docs.set(name, lines.slice(start, i).join('\n'));
    });
    return docs;
}

function android() {
    const old = existsSync(wiconsPath) ? readFileSync(wiconsPath, 'utf8') : '';
    const docs = currentDocs(old);
    const keys = Object.keys(manifest).filter((k) => /^[A-Z]/.test(k));
    // Keep the file's order; new icons go at the end.
    const order = [...[...docs.keys()].filter((k) => keys.includes(k)), ...keys.filter((k) => !docs.has(k))];
    const vals = order.map((name) => {
        const entry = manifest[name];
        const parts = paths(svgFor(entry), entry.style).map((p) =>
            p.stroke ? `stroke("${p.d}")` : `fill("${p.d}"${p.evenOdd ? ', evenOdd = true' : ''})`);
        const doc = docs.get(name);
        return `${doc ? doc + '\n' : ''}    val ${name}: ImageVector by lazy { icon("${name}", ${parts.join(', ')}) }`;
    });
    const out = `package app.wallhop.ui.design

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// Generated by brand/icons/generate.mjs from brand/icons/icons.json, which the Mac app's icons
// come from too, so a concept looks the same on both. Solid for tabs, tiles and status; stroke
// (${STROKE_WIDTH} on the 24 grid) for small controls. Edit the manifest (or the KDoc here) and
// regenerate rather than editing paths by hand.

/** The app's icon set. */
object WIcons {
${vals.join('\n')}
}

private class Part(val d: String, val stroke: Boolean, val evenOdd: Boolean = false)

private fun fill(d: String, evenOdd: Boolean = false) = Part(d, stroke = false, evenOdd = evenOdd)
private fun stroke(d: String) = Part(d, stroke = true)

/** Drawn black, so \`Icon(tint)\` and \`ColorFilter.tint\` recolour fills and strokes alike. */
private fun icon(name: String, vararg parts: Part): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, viewportWidth = 24f, viewportHeight = 24f).apply {
        for (part in parts) {
            if (part.stroke) {
                addPath(
                    pathData = addPathNodes(part.d),
                    fill = null,
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = ${STROKE_WIDTH}f,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            } else {
                addPath(
                    pathData = addPathNodes(part.d),
                    fill = SolidColor(Color.Black),
                    pathFillType = if (part.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                )
            }
        }
    }.build()
`;
    writeFileSync(wiconsPath, out);
    const gone = [...docs.keys()].filter((k) => !keys.includes(k));
    console.log(`WIcons.kt: ${order.length} icons${gone.length ? ` (dropped ${gone.join(', ')})` : ''}`);
}

// MARK: Mac

function mac() {
    mkdirSync(macDir, { recursive: true });
    const keys = Object.keys(manifest).filter((k) => /^[a-z]/.test(k));
    for (const key of keys) {
        const entry = manifest[key];
        let svg = svgFor(entry);
        if (entry.style === 'stroke') svg = svg.replace(/stroke-width="[^"]*"/g, `stroke-width="${STROKE_WIDTH}"`);
        writeFileSync(join(macDir, `${key}.svg`), svg.trim() + '\n');
    }
    for (const file of readdirSync(macDir)) {
        if (file.endsWith('.svg') && !keys.includes(file.slice(0, -4))) unlinkSync(join(macDir, file));
    }
    console.log(`mac/Resources/Icons: ${keys.length} icons`);
}

android();
mac();
